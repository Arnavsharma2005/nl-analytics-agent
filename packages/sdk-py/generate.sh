#!/bin/sh
# Regenerate src/nl_analytics/models.py from the API's OpenAPI spec (apps/web-next/openapi.json, written by
# apps/api/scripts/export_openapi.py). CI runs this and fails if the result differs from what is committed.
set -e
cd "$(dirname "$0")"
datamodel-codegen --input ../../apps/web-next/openapi.json --input-file-type openapi \
  --output src/nl_analytics/models.py --output-model-type pydantic_v2.BaseModel --target-python-version 3.11 \
  --enum-field-as-literal all --use-schema-description --use-standard-collections --use-union-operator \
  --disable-timestamp --custom-file-header "# Generated by packages/sdk-py/generate.sh from the API's OpenAPI spec. Do not edit."
